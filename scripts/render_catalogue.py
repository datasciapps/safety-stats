"""Write docs/diagnostics.md, the catalogue of diagnostic codes and assumptions, from the registry.

The page is generated from ``inspect_safety_stats.registry`` and never edited by hand:

    python scripts/render_catalogue.py            # rewrite docs/diagnostics.md
    python scripts/render_catalogue.py --check    # exit 1 when the committed page is stale

``tests/test_diagnostics_catalogue.py`` runs the check, so a registry change that leaves the
page behind fails the test suite. Exit status: 0 written or up to date, 1 stale.
"""

from __future__ import annotations

import argparse
import re
import sys
import textwrap
from collections.abc import Iterable
from pathlib import Path

from inspect_safety_stats.registry import (
    ASSUMPTIONS,
    CODES,
    EFFECTS,
    SOURCE_KINDS,
    AssumptionEntry,
    CodeEntry,
    checked_by,
)

ROOT = Path(__file__).resolve().parents[1]
PAGE = ROOT / "docs" / "diagnostics.md"
WIDTH = 100

_INTRO = (
    "Every diagnostic code the package writes into a report, and every assumption a report's "
    "results rest on, with what it means in any analysis: the assumption it reports on, what it "
    "does to the results, and what to change. A report's diagnostics say what was found in one "
    "analysis; this page says what each code means. See "
    "[Interpreting results](interpretation.md) for how diagnostics bear on integrity and claims."
)

_GENERATED = (
    "<!-- Generated by scripts/render_catalogue.py from src/inspect_safety_stats/registry.py. "
    "Do not edit by hand: change the registry and run the script. -->"
)


def _wrap(text: str, *, first: str = "", rest: str = "") -> list[str]:
    """Text wrapped to the page width, never inside a word or at a hyphen."""

    return textwrap.wrap(
        text,
        width=WIDTH,
        initial_indent=first,
        subsequent_indent=rest,
        break_long_words=False,
        break_on_hyphens=False,
    )


def _field(name: str, text: str) -> list[str]:
    """A bullet that names a field of an entry and gives its text."""

    return _wrap(f"**{name}:** {text}", first="- ", rest="  ")


def _cell(text: str) -> str:
    return text.replace("|", "\\|")


def _anchor(heading: str) -> str:
    """The anchor GitHub gives a heading: lower case, punctuation dropped, spaces as hyphens."""

    return re.sub(r"[^\w\- ]", "", heading.lower()).replace(" ", "-")


def _kind_heading(kind: str) -> str:
    return f"`{kind}` codes"


def _code_heading(code: str) -> str:
    return f"`{code}`"


def _assumption_heading(assumption: str) -> str:
    return f"Assumption `{assumption}`"


def _code_link(code: str) -> str:
    return f"[`{code}`](#{_anchor(_code_heading(code))})"


def _assumption_link(assumption: str) -> str:
    return f"[`{assumption}`](#{_anchor(_assumption_heading(assumption))})"


def _links(items: Iterable[str]) -> str:
    return ", ".join(items)


def _assumption_section(entry: AssumptionEntry) -> list[str]:
    lines = [f"### {_assumption_heading(entry.id)}", ""]
    lines += _wrap(entry.statement)
    lines.append("")
    lines += _field("Input", f"[{entry.source}](#input-kinds)")
    if entry.plan_field is None:
        lines += _field("Plan field", "none: no plan field changes it")
    else:
        default = "none: the plan must state it" if entry.default is None else f"`{entry.default}`"
        lines += _field("Plan field", f"`{entry.plan_field}`, default {default}")
    lines += _field("If it is wrong", entry.if_wrong)
    for setting in entry.by_setting:
        text = setting.statement
        if setting.if_wrong is not None:
            text += f" If it is wrong: {setting.if_wrong}"
        lines += _field(f"With `{setting.value}`", text)
    lines += _field("Remedy", entry.remedy)
    codes = checked_by(entry.id)
    lines += _field(
        "Checked by",
        _links(_code_link(code) for code in codes) if codes else "no diagnostic code",
    )
    lines.append("")
    return lines


def _code_section(entry: CodeEntry) -> list[str]:
    lines = [f"#### {_code_heading(entry.code)}", ""]
    lines += _field("Severity", ", ".join(entry.severities))
    lines += _field("Effect", f"[{entry.effect}](#effects)")
    lines += _field("Assumption", entry.assumption)
    lines += _field("Consequence", entry.consequence)
    lines += _field("Remedy", entry.remedy)
    if entry.assumptions:
        lines += _field("Checks", _links(_assumption_link(name) for name in entry.assumptions))
    lines.append("")
    return lines


def _check_anchors() -> None:
    """Fail loudly when two headings of the page would share an anchor."""

    headings = [_code_heading(code) for code in CODES]
    headings += [_assumption_heading(name) for name in ASSUMPTIONS]
    headings += ["Effects", "Input kinds", "Assumptions", "Diagnostic codes"]
    headings += [_kind_heading(kind) for kind in SOURCE_KINDS]
    anchors = [_anchor(heading) for heading in headings]
    clashes = sorted({anchor for anchor in anchors if anchors.count(anchor) > 1})
    if clashes:
        raise ValueError(f"headings would share the anchors {clashes}")


def render() -> str:
    """The catalogue page, as it should be committed."""

    _check_anchors()
    lines = [_GENERATED, "", "# Diagnostic codes and assumptions", ""]
    lines += _wrap(_INTRO)
    lines += ["", "## Effects", ""]
    lines += _wrap("What a diagnostic code does to the results, given as each code's effect.")
    lines += ["", "| Effect | What it means |", "|---|---|"]
    lines += [f"| {effect} | {_cell(text)} |" for effect, text in EFFECTS.items()]
    lines += ["", "## Input kinds", ""]
    lines += _wrap("The kind of input an assumption or a code concerns: where to look first.")
    lines += ["", "| Input | What it covers |", "|---|---|"]
    lines += [f"| {kind} | {_cell(text)} |" for kind, text in SOURCE_KINDS.items()]
    lines += ["", "## Assumptions", ""]
    lines += _wrap(
        "The assumptions a report's results can rest on, the plan field that sets or relaxes "
        "each, and the diagnostic codes that report evidence against it."
    )
    lines.append("")
    for name in sorted(ASSUMPTIONS):
        lines += _assumption_section(ASSUMPTIONS[name])
    lines += ["## Diagnostic codes", ""]
    lines += _wrap(
        "The codes by the kind of input they concern, in alphabetical order within each kind."
    )
    lines.append("")
    for kind in SOURCE_KINDS:
        codes = sorted(code for code, entry in CODES.items() if entry.source == kind)
        if not codes:
            continue
        lines += [f"### {_kind_heading(kind)}", ""]
        lines += _wrap(SOURCE_KINDS[kind])
        lines.append("")
        for code in codes:
            lines += _code_section(CODES[code])
    while lines[-1] == "":
        lines.pop()
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="do not write; exit 1 when the committed page differs from the registry",
    )
    args = parser.parse_args(argv)
    page = render()
    if args.check:
        # Bytes, not text: reading text turns CRLF into LF, so a page checked out or edited
        # with CRLF line ends would pass while differing from what this writes.
        current = PAGE.read_bytes() if PAGE.exists() else None
        if current != page.encode("utf-8"):
            print(
                f"{PAGE.relative_to(ROOT).as_posix()} is stale: run "
                "python scripts/render_catalogue.py",
                file=sys.stderr,
            )
            return 1
        print(f"{PAGE.relative_to(ROOT).as_posix()} is up to date")
        return 0
    PAGE.write_text(page, encoding="utf-8", newline="\n")
    print(f"wrote {PAGE.relative_to(ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
