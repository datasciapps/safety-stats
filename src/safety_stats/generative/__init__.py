"""Generative hierarchy evaluation.

The fixed-design engine conditions on a materialized set of prompts. This package covers
the case where the prompts do not exist yet: the evaluator declares a structural taxonomy
with target weights and a frozen stochastic rewrite kernel, and prompts are generated by
sampling that design. Path selection and rewrite generation are then sources of uncertainty
in their own right.

The generative pipeline is experimental: its public surface,
``safety_stats.generative.__all__``, may change in any minor release.

The public surface is organised around what you are trying to do.

**Run an evaluation.** Two phases, because an Inspect run happens between them::

    from safety_stats.generative import materialize_run, analyze_run

    run = materialize_run("plan.yaml", "artifacts/", kernel="mypkg:build_kernel")
    # ... evaluate run.dataset with Inspect, then ...
    report = analyze_run("plan.yaml", "artifacts/", "logs/")
    report.write("report/")

**Decide a budget first**, from the taxonomy alone, before generating anything::

    from safety_stats.generative import compile_taxonomy, forecast, load_generative_plan

    plan = load_generative_plan("plan.yaml")
    taxonomy = compile_taxonomy(plan, base_path=".")
    forecast(taxonomy, plan, total_rewrites=1200, assumed_rate=0.03)

**Supply a rewrite kernel.** This is the one piece you must write: any object with a
``rewrite`` method matching :class:`RewriteKernel`. Under ``rewrite.output: conversation``
(experimental) it returns whole conversations as :class:`ChatTurn` messages.
``DeterministicFakeKernel`` stands in for it in tests and dry runs.

**Compose your own flow** with the lower-level pieces -- ``plan_design``,
``draw_selections``, ``execute_rewrites``, ``join_outcomes``, ``estimate_tree`` -- when the
two-phase runner does not fit.

Names not listed in ``__all__`` are internal and may change without notice.
"""

